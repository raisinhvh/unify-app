#!/usr/bin/env node
/**
 * Switch Unify's UI font (titles, labels, body). The code font is not touched.
 *
 *   node scripts/set-font.mjs "Anonymous Pro"
 *   node scripts/set-font.mjs "Space Grotesk"
 *   node scripts/set-font.mjs --current
 *
 * Any Google font works: it is installed from Fontsource (@fontsource/<id>) so the app
 * stays offline. The script rewrites src/renderer/theme/ui-font.ts with that font's real
 * weights, and removes the previous UI font package. A running dev server reloads on its own.
 */
import { execSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const unifyRoot = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const rendererDir = join(unifyRoot, 'src', 'renderer');
const generatedFile = join(rendererDir, 'theme', 'ui-font.ts');
const codeFontPackage = '@fontsource/jetbrains-mono';

// The package.json that owns the renderer's font dependencies (root once merged, renderer until then).
function findPackageDir() {
	for (const dir of [unifyRoot, rendererDir]) {
		const manifestPath = join(dir, 'package.json');
		if (!existsSync(manifestPath)) continue;
		const manifest = JSON.parse(readFileSync(manifestPath, 'utf8'));
		const dependencies = { ...manifest.dependencies, ...manifest.devDependencies };
		if (Object.keys(dependencies).some((name) => name.startsWith('@fontsource/'))) return dir;
	}
	return rendererDir;
}

function readCurrentPackage() {
	if (!existsSync(generatedFile)) return undefined;
	const match = readFileSync(generatedFile, 'utf8').match(/@fontsource\/[a-z0-9-]+/);
	return match ? match[0] : undefined;
}

function fallbackFor(category) {
	if (category === 'monospace') return 'ui-monospace, monospace';
	if (category === 'serif') return 'ui-serif, Georgia, serif';
	return 'system-ui, sans-serif';
}

const argument = process.argv.slice(2).join(' ').trim();
if (!argument || argument === '--help') {
	console.log('Usage: node scripts/set-font.mjs "<Google font family>"   |   --current');
	process.exit(argument ? 0 : 1);
}
if (argument === '--current') {
	console.log(readCurrentPackage() ?? 'No UI font set yet.');
	process.exit(0);
}

const fontId = argument.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');
const packageName = `@fontsource/${fontId}`;
const packageDir = findPackageDir();
const installedDir = join(packageDir, 'node_modules', packageName);

if (!existsSync(join(installedDir, 'metadata.json'))) {
	console.log(`Installing ${packageName}...`);
	try {
		execSync(`npm install ${packageName}@^5`, { cwd: packageDir, stdio: 'inherit' });
	} catch {
		console.error(`\nCould not install ${packageName}. Check the family name on https://fontsource.org.`);
		process.exit(1);
	}
}

const metadata = JSON.parse(readFileSync(join(installedDir, 'metadata.json'), 'utf8'));
const weights = metadata.weights.map(Number).sort((a, b) => a - b);
const hasItalic = metadata.styles.includes('italic');

const imports = [];
for (const weight of weights) {
	imports.push(`import '${packageName}/${weight}.css';`);
	if (hasItalic) imports.push(`import '${packageName}/${weight}-italic.css';`);
}

const source = `/**
 * GENERATED by scripts/set-font.mjs. Change the UI font with:
 *   node scripts/set-font.mjs "<Google font family>"
 * ${metadata.family} ships weights ${weights.join(', ')}. Heavier CSS weights fall back to the nearest one.
 */
${imports.join('\n')}

export const UI_FONT_FAMILY = "'${metadata.family}', ${fallbackFor(metadata.category)}";
export const UI_FONT_WEIGHTS = [${weights.join(', ')}] as const;
`;
const previousPackage = readCurrentPackage();
writeFileSync(generatedFile, source);

if (previousPackage && previousPackage !== packageName && previousPackage !== codeFontPackage) {
	console.log(`Removing previous UI font ${previousPackage}...`);
	execSync(`npm uninstall ${previousPackage}`, { cwd: packageDir, stdio: 'inherit' });
}

console.log(`UI font is now ${metadata.family} (weights ${weights.join(', ')}).`);
