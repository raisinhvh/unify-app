/**
 * Local Hub registry: the development catalogue in `fixtures/`, with a canned download.
 *
 * It exists so the Hub screen and the install flow can be exercised without a network or a published
 * registry. `createHubRegistry()` uses this by default; the GitHub registry is opt-in. Publishing applies the
 * same approved-accounts rule as the GitHub registry, using the `fixtures/publishers.json` list.
 */
import { promises as fsp } from 'node:fs';
import * as path from 'node:path';
import type { GithubAuth } from '../unify/github';
import { catalogueReadme, catalogueState, findCataloguePack } from './fixtures/catalogue';
import { packJavaScriptFor, packSourceFor } from './fixtures/packSource';
import { APPROVED_PUBLISHERS } from './fixtures/publishers';
import { publishResultFor } from './publishing';
import { HubPackDetail, HubPublishResult, HubRegistry, HubState } from './types';

const INSTALL_SCRIPT = [
  '// Generated by the Unify local Hub fixture. It only leaves a marker so dev installs are visible.',
  "const fs = require('node:fs');",
  "fs.writeFileSync(require('node:path').join(process.cwd(), 'install-ran.txt'), 'Unify local Hub fixture install script ran.\\n');",
  '',
].join('\n');

export class LocalHubRegistry implements HubRegistry {
  public readonly id = 'local';

  public async state(): Promise<HubState> {
    return catalogueState();
  }

  public async detail(id: string): Promise<HubPackDetail | undefined> {
    const pack = findCataloguePack(id);
    return pack ? { pack, readme: catalogueReadme(pack) } : undefined;
  }

  public async download(id: string, destination: string): Promise<void> {
    if (!findCataloguePack(id)) throw new Error(`Unknown Hub pack "${id}".`);
    await fsp.mkdir(destination, { recursive: true });
    await fsp.writeFile(path.join(destination, 'pack.ts'), packSourceFor(id), 'utf8');
    await fsp.writeFile(path.join(destination, 'pack.js'), packJavaScriptFor(id), 'utf8');
    await fsp.writeFile(path.join(destination, 'install.js'), INSTALL_SCRIPT, 'utf8');
  }

  public async publish(auth: GithubAuth | undefined): Promise<HubPublishResult> {
    return publishResultFor(auth, APPROVED_PUBLISHERS);
  }
}
