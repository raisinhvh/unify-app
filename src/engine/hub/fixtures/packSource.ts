/**
 * Pack contents for the local Hub fixture.
 *
 * The Hub catalogue uses ids such as `roblox-studio`, but a toolpack id may only contain lowercase letters,
 * digits and underscores. `toolpackIdFor` maps the Hub id to a valid pack id; installs write that id and keep
 * the original Hub id in `meta.json.hubId` so the extension can match the two lists.
 *
 * Both a TypeScript source and its CommonJS build are produced: the toolpack registry loads `pack.js` with
 * `require`, and the Hub install flow compiles the TypeScript when a pack only ships `pack.ts`.
 */
import { findCataloguePack } from './catalogue';
import { HubPack } from '../types';

const TOOLPACK_NAME = /^[a-z][a-z0-9_]{0,31}$/;

/** `roblox-studio` -> `roblox_studio`, `web-search` -> `web_search`. */
export function toolpackIdFor(hubId: string): string {
  const sanitized = hubId.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '');
  const withLetter = /^[a-z]/.test(sanitized) ? sanitized : `pack_${sanitized}`;
  const id = withLetter.slice(0, 32);
  if (!TOOLPACK_NAME.test(id)) throw new Error(`Cannot turn Hub id "${hubId}" into a toolpack id.`);
  return id;
}

/** Short tool names: the catalogue lists `roblox_tree`, the pack defines `tree` and the registry prefixes its id. */
function toolNames(pack: HubPack): string[] {
  const prefix = `${pack.id.split('-')[0]}_`;
  return pack.tools.map(name => {
    const short = name.startsWith(prefix) ? name.slice(prefix.length) : name;
    const safe = short.toLowerCase().replace(/[^a-z0-9_]+/g, '_').replace(/^_+|_+$/g, '').slice(0, 32);
    return TOOLPACK_NAME.test(safe) ? safe : `tool_${safe}`.slice(0, 32);
  });
}

function uniqueToolNames(pack: HubPack): string[] {
  const seen = new Set<string>();
  const names: string[] = [];
  for (const name of toolNames(pack)) {
    let candidate = name;
    let suffix = 1;
    while (seen.has(candidate)) {
      candidate = `${name.slice(0, 28)}_${suffix++}`;
    }
    seen.add(candidate);
    names.push(candidate);
  }
  return names;
}

export interface FixturePack {
  id: string;
  hubId: string;
  name: string;
  description: string;
  tools: string[];
}

export function fixturePack(hubId: string): FixturePack {
  const pack = findCataloguePack(hubId);
  if (!pack) throw new Error(`Unknown Hub pack "${hubId}".`);
  return {
    id: toolpackIdFor(pack.id),
    hubId: pack.id,
    name: pack.name,
    description: pack.description,
    tools: uniqueToolNames(pack),
  };
}

function toolResult(pack: HubPack, tool: string): string {
  return `${pack.name}: ${tool} (local Hub fixture, nothing was changed).`;
}

/** TypeScript source for the fixture pack: `export default` a valid toolpack definition. */
export function packSourceFor(hubId: string): string {
  const pack = findCataloguePack(hubId);
  if (!pack) throw new Error(`Unknown Hub pack "${hubId}".`);
  const fixture = fixturePack(hubId);
  const tools = fixture.tools.map(tool => [
    '    {',
    `      name: ${JSON.stringify(tool)},`,
    `      description: ${JSON.stringify(`${pack.name} fixture tool.`)},`,
    '      run() {',
    `        return ${JSON.stringify(toolResult(pack, tool))};`,
    '      },',
    '    },',
  ].join('\n')).join('\n');
  return [
    '// Generated by the Unify local Hub fixture. No network, no real integrations.',
    'export default {',
    `  name: ${JSON.stringify(fixture.id)},`,
    `  description: ${JSON.stringify(pack.description)},`,
    '  tools: [',
    tools,
    '  ],',
    '};',
    '',
  ].join('\n');
}

/** CommonJS build of the same pack, for catalogues that ship `pack.ts` and `pack.js` together. */
export function packJavaScriptFor(hubId: string): string {
  const pack = findCataloguePack(hubId);
  if (!pack) throw new Error(`Unknown Hub pack "${hubId}".`);
  const fixture = fixturePack(hubId);
  const tools = fixture.tools.map(tool => [
    '    {',
    `      name: ${JSON.stringify(tool)},`,
    `      description: ${JSON.stringify(`${pack.name} fixture tool.`)},`,
    '      run: function () {',
    `        return ${JSON.stringify(toolResult(pack, tool))};`,
    '      },',
    '    },',
  ].join('\n')).join('\n');
  return [
    '// Generated by the Unify local Hub fixture.',
    'const pack = {',
    `  name: ${JSON.stringify(fixture.id)},`,
    `  description: ${JSON.stringify(pack.description)},`,
    '  tools: [',
    tools,
    '  ],',
    '};',
    'module.exports = { default: pack };',
    '',
  ].join('\n');
}
